-- 014: registro de actividad (quién hizo qué y cuándo), para el módulo Actividad del admin.
-- Ejecutar después de 013. No borra datos y se puede volver a ejecutar completa.
--
--   * registro_actividad: una fila por cada cambio hecho desde la app (reservas, sesiones, puestos,
--     tatuadores y arriendos), con quién lo hizo, un resumen legible y el detalle de los cambios.
--   * Solo se agregan filas: el backend no puede editarlas ni borrarlas (no tiene esos permisos),
--     así el registro es confiable.
--   * registro_actividad_local: la misma tabla con la fecha en hora de Santiago, para filtrar por día.
BEGIN;

CREATE TABLE IF NOT EXISTS public.registro_actividad (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actor uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  actor_nombre text NOT NULL,
  actor_rol text NOT NULL,
  categoria text NOT NULL CHECK (categoria IN ('reserva', 'sesion', 'puesto', 'tatuador', 'arriendo')),
  accion text NOT NULL CHECK (char_length(accion) <= 40),
  entidad_id text,
  resumen text NOT NULL CHECK (char_length(resumen) <= 500),
  detalle jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS registro_actividad_creado_idx ON public.registro_actividad (creado_en DESC, id DESC);
CREATE INDEX IF NOT EXISTS registro_actividad_actor_idx ON public.registro_actividad (actor, id DESC);
CREATE INDEX IF NOT EXISTS registro_actividad_categoria_idx ON public.registro_actividad (categoria, id DESC);

CREATE OR REPLACE VIEW public.registro_actividad_local WITH (security_invoker = on) AS
SELECT r.*, (r.creado_en AT TIME ZONE 'America/Santiago')::date AS fecha_local
FROM public.registro_actividad r;

-- Permisos: solo el backend, y solo para leer y agregar.
ALTER TABLE public.registro_actividad ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.registro_actividad, public.registro_actividad_local FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT ON public.registro_actividad TO service_role;
GRANT SELECT ON public.registro_actividad_local TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;


-- 013: arriendo de los tatuadores según su modalidad.
-- Ejecutar después de 012. No borra datos y se puede volver a ejecutar completa.
--
--   * Agrega la modalidad "Rotativo light" si no existe (quedan Full, Rotativo, Compartido, Guest y Rotativo light).
--   * modalidad_tarifas: cuánto paga cada modalidad y desde qué mes (un cambio de precio no altera los meses anteriores).
--   * modalidad_historial: qué modalidad tuvo cada tatuador en cada mes. Se llena sola al asignar o cambiar
--     usuarios.modalidad; la primera modalidad de un tatuador vale también para los meses anteriores.
--   * pagos_arriendo: los pagos que registra el admin, por tatuador y mes.
--
-- Tarifas iniciales:
--   Full            $220.000 al mes.
--   Compartido      $120.000 al mes, cada titular.
--   Rotativo        $12.000 por turno (sesión no cancelada); mínimo $60.000 al mes, que cubre los primeros 5 turnos.
--   Rotativo light  $12.000 por turno; mínimo $36.000 al mes (3 turnos).
--   Guest           $15.000 por día con sesiones; con 5 o más días en el mes, $12.000 cada día.
BEGIN;

-- 1. Modalidad "Rotativo light" -----------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.modalidad WHERE lower(trim(nombre)) = 'rotativo light') THEN
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'modalidad' AND column_name = 'id'
        AND (column_default IS NOT NULL OR is_identity = 'YES')
    ) THEN
      INSERT INTO public.modalidad(nombre) VALUES ('Rotativo light');
    ELSE
      INSERT INTO public.modalidad(id, nombre) SELECT COALESCE(max(id), 0) + 1, 'Rotativo light' FROM public.modalidad;
    END IF;
  END IF;
END;
$$;

-- 2. Tarifas por modalidad --------------------------------------------------------------------
-- cobro: 'mensual' (monto fijo), 'turno' (monto por turno, con minimo_mensual) o
--        'dia' (monto por día; desde dias_reducido días en el mes, monto_reducido cada día).
CREATE TABLE IF NOT EXISTS public.modalidad_tarifas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  modalidad bigint NOT NULL REFERENCES public.modalidad(id) ON DELETE CASCADE,
  vigente_desde date NOT NULL,
  cobro text NOT NULL CHECK (cobro IN ('mensual', 'turno', 'dia')),
  monto bigint NOT NULL CHECK (monto >= 0),
  minimo_mensual bigint NOT NULL DEFAULT 0 CHECK (minimo_mensual >= 0),
  monto_reducido bigint CHECK (monto_reducido >= 0),
  dias_reducido integer CHECK (dias_reducido > 0),
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT modalidad_tarifas_mes_check CHECK (extract(day FROM vigente_desde) = 1),
  CONSTRAINT modalidad_tarifas_unica UNIQUE (modalidad, vigente_desde)
);

INSERT INTO public.modalidad_tarifas(modalidad, vigente_desde, cobro, monto, minimo_mensual, monto_reducido, dias_reducido)
SELECT m.id, DATE '2000-01-01', t.cobro, t.monto, t.minimo, t.reducido, t.dias
FROM public.modalidad m
JOIN (VALUES
  ('full',           'mensual', 220000::bigint,     0::bigint, NULL::bigint, NULL::integer),
  ('compartido',     'mensual', 120000,             0,         NULL,         NULL),
  ('rotativo',       'turno',    12000,         60000,         NULL,         NULL),
  ('rotativo light', 'turno',    12000,         36000,         NULL,         NULL),
  ('guest',          'dia',      15000,             0,        12000,            5)
) AS t(nombre, cobro, monto, minimo, reducido, dias) ON t.nombre = lower(trim(m.nombre))
ON CONFLICT (modalidad, vigente_desde) DO NOTHING;

-- 3. Historial de modalidad de cada tatuador --------------------------------------------------
CREATE TABLE IF NOT EXISTS public.modalidad_historial (
  tatuador uuid NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  desde date NOT NULL,
  modalidad bigint REFERENCES public.modalidad(id) ON DELETE SET NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tatuador, desde),
  CONSTRAINT modalidad_historial_mes_check CHECK (extract(day FROM desde) = 1)
);

-- Al asignar o cambiar la modalidad, vale desde el mes actual (hora de Santiago).
-- Si el tatuador no tenía historial, vale también para los meses anteriores.
-- SECURITY DEFINER: también corre cuando Supabase Auth crea el perfil al aceptar una invitación.
CREATE OR REPLACE FUNCTION public.okami_registrar_modalidad()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_desde date := date_trunc('month', now() AT TIME ZONE 'America/Santiago')::date;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.modalidad IS NOT DISTINCT FROM OLD.modalidad THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'INSERT' AND NEW.modalidad IS NULL THEN
    RETURN NEW;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.modalidad_historial WHERE tatuador = NEW.id) THEN
    v_desde := DATE '2000-01-01';
  END IF;
  INSERT INTO public.modalidad_historial(tatuador, desde, modalidad)
  VALUES (NEW.id, v_desde, NEW.modalidad)
  ON CONFLICT (tatuador, desde) DO UPDATE SET modalidad = EXCLUDED.modalidad, creado_en = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS okami_registrar_modalidad ON public.usuarios;
CREATE TRIGGER okami_registrar_modalidad AFTER INSERT OR UPDATE OF modalidad ON public.usuarios
FOR EACH ROW EXECUTE FUNCTION public.okami_registrar_modalidad();

-- Tatuadores que ya tienen modalidad: su historial empieza con ella.
INSERT INTO public.modalidad_historial(tatuador, desde, modalidad)
SELECT u.id, DATE '2000-01-01', u.modalidad FROM public.usuarios u
WHERE u.modalidad IS NOT NULL
ON CONFLICT (tatuador, desde) DO NOTHING;

-- 4. Pagos del arriendo -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pagos_arriendo (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tatuador uuid NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  periodo date NOT NULL,
  monto bigint NOT NULL CHECK (monto > 0),
  pagado_en date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Santiago')::date,
  nota text CHECK (char_length(nota) <= 200),
  registrado_por uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pagos_arriendo_mes_check CHECK (extract(day FROM periodo) = 1)
);
CREATE INDEX IF NOT EXISTS pagos_arriendo_periodo_idx ON public.pagos_arriendo(periodo);
CREATE INDEX IF NOT EXISTS pagos_arriendo_tatuador_idx ON public.pagos_arriendo(tatuador);

-- 5. Permisos: solo el backend (service_role) -------------------------------------------------
ALTER TABLE public.modalidad_tarifas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.modalidad_historial ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagos_arriendo ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.modalidad_tarifas, public.modalidad_historial, public.pagos_arriendo FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.modalidad_tarifas, public.modalidad_historial, public.pagos_arriendo TO service_role;
GRANT SELECT ON public.modalidad TO service_role;
GRANT UPDATE (modalidad) ON public.usuarios TO service_role;
REVOKE ALL ON FUNCTION public.okami_registrar_modalidad() FROM PUBLIC, anon, authenticated;
NOTIFY pgrst, 'reload schema';
COMMIT;


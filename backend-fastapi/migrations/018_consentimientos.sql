-- 018: consentimiento informado (DS 304/2002) con folio correlativo.
-- Ejecutar en Supabase SQL Editor. Se puede ejecutar más de una vez (idempotente).
--
-- Cada consentimiento guarda los datos que se imprimen en la plantilla (docs/plantilla_docs):
-- tatuador, cliente, representante (si el cliente es menor de edad) y el trabajo a realizar.
-- Incluye datos de salud (ley 19.628): solo el backend (service_role) lee y escribe; RLS bloquea la clave pública.
-- No se editan ni se borran desde la app: son el respaldo de lo que firmó el cliente.

BEGIN;

CREATE TABLE IF NOT EXISTS public.consentimientos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  folio bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  fecha date NOT NULL,
  reserva uuid REFERENCES public.reservas(id) ON DELETE SET NULL,
  tatuador uuid NOT NULL REFERENCES public.usuarios(id),
  tatuador_nombre text NOT NULL CHECK (char_length(tatuador_nombre) BETWEEN 1 AND 120),
  tatuador_rut text NOT NULL CHECK (char_length(tatuador_rut) BETWEEN 2 AND 12),
  tatuador_nacimiento date,
  tatuador_telefono text CHECK (char_length(tatuador_telefono) <= 20),
  cliente_nombre text NOT NULL CHECK (char_length(cliente_nombre) BETWEEN 1 AND 120),
  cliente_rut text NOT NULL CHECK (char_length(cliente_rut) BETWEEN 2 AND 12),
  cliente_nacimiento date NOT NULL,
  cliente_telefono text CHECK (char_length(cliente_telefono) <= 20),
  cliente_direccion text CHECK (char_length(cliente_direccion) <= 120),
  representante_nombre text CHECK (char_length(representante_nombre) <= 120),
  representante_rut text CHECK (char_length(representante_rut) <= 12),
  representante_nacimiento date,
  representante_telefono text CHECK (char_length(representante_telefono) <= 20),
  descripcion text NOT NULL CHECK (char_length(descripcion) BETWEEN 1 AND 160),
  zona_cuerpo text NOT NULL CHECK (char_length(zona_cuerpo) BETWEEN 1 AND 80),
  condiciones text CHECK (char_length(condiciones) <= 160),
  tipo_tatuaje text NOT NULL CHECK (tipo_tatuaje IN ('Nuevo', 'Cover', 'Retoque')),
  creado_por uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS consentimientos_creado_idx ON public.consentimientos (creado_en DESC);
CREATE INDEX IF NOT EXISTS consentimientos_tatuador_idx ON public.consentimientos (tatuador, creado_en DESC);
CREATE INDEX IF NOT EXISTS consentimientos_cliente_rut_idx ON public.consentimientos (cliente_rut);

ALTER TABLE public.consentimientos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.consentimientos FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.consentimientos TO service_role;

COMMENT ON TABLE public.consentimientos IS 'Consentimiento informado de tatuaje (DS 304/2002). Contiene datos de salud: solo service_role.';

-- Registro de actividad: nueva categoría "consentimiento".
ALTER TABLE public.registro_actividad DROP CONSTRAINT IF EXISTS registro_actividad_categoria_check;
ALTER TABLE public.registro_actividad ADD CONSTRAINT registro_actividad_categoria_check
  CHECK (categoria IN ('reserva', 'sesion', 'puesto', 'tatuador', 'arriendo', 'consentimiento'));

NOTIFY pgrst, 'reload schema';
COMMIT;

